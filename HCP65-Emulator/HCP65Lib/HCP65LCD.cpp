//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDBoard::Read(uint32 uiOffset)
{
	if (uiOffset < DEVICE_ROM_SIZE)
	{
		return mcROM.Read(uiOffset);
	}
	if (uiOffset < 0x800)
	{
		return Access(uiOffset & 0x0F, false, 0);
	}
	return 0xFF;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDBoard::Write(uint32 uiOffset, uint8 uiValue)
{
	if ((uiOffset >= DEVICE_ROM_SIZE) && (uiOffset < 0x800))
	{
		Access(uiOffset & 0x0F, true, uiValue);
	}
}


//////////////////////////////////////////////////////////////////////////
//
// An access to $400-$407 sets the display's pins from its address, the
// display seeing the byte latched before it; a write then latches its
// byte.  $408-$40B read the SNES latches.
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDBoard::Access(uint32 uiRegister, bool bWrite, uint8 uiValue)
{
	uint8	uiResult;

	if (mpcHCP65 && (mpcHCP65->NumCycles() > muiCycle))
	{
		muiCycle = mpcHCP65->NumCycles();
	}
	PowerOn();
	if (uiRegister >= HCP65_LCD_SNES_1_LOW)
	{
		if (bWrite || (uiRegister > HCP65_LCD_SNES_2_HIGH))
		{
			return 0xFF;
		}
		return ReadController((uiRegister - HCP65_LCD_SNES_1_LOW) / 2, (uiRegister & 1) != 0);
	}

	mcMutex.Lock();
	muiPins = (uint8)uiRegister;
	mcController.SetPins((muiPins & HCP65_LCD_E) != 0, (muiPins & HCP65_LCD_RS) != 0, (muiPins & HCP65_LCD_READ) != 0, muiData, muiCycle);
	if (bWrite)
	{
		muiData = uiValue;
	}
	if (!(muiPins & HCP65_LCD_READ))
	{
		uiResult = muiData;
	}
	else if (mcController.IsDriving())
	{
		uiResult = mcController.GetOutput(muiCycle);
	}
	else
	{
		uiResult = 0xFF;
	}
	mcMutex.Unlock();
	return uiResult;
}


//////////////////////////////////////////////////////////////////////////
//
// Its latches, 0 for pressed: the high register is the first eight
// buttons it sends, the low one the last four and four that are never
// pressed.  They follow the buttons unless the board is held in reset.
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDBoard::ReadController(int iController, bool bHigh)
{
	uint16	uiSent;

	if (!mbHeldInReset)
	{
		mauiLatched[iController] = mauiButtons[iController];
	}
	uiSent = (uint16)~mauiLatched[iController];
	return bHigh ? (uint8)uiSent : (uint8)((uiSent >> 8) | 0xF0);
}


