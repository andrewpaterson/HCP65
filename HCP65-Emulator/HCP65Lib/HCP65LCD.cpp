//////////////////////////////////////////////////////////////////////////
//
// As power leaves it: busy with its own reset (PowerOn).
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::Init(uint64 uiCyclesPerSecond)
{
	muiCyclesPerSecond = uiCyclesPerSecond;
	memset(mauiCGRAM, 0, HCP65_LCD_CGRAM_SIZE);
	mbE = false;
	mbRS = false;
	mbRead = false;
	muiIgnored = 0;
	PowerOn(0);
}


//////////////////////////////////////////////////////////////////////////
//
// Its reset on power: the display cleared and off, eight bit, one line,
// the address counter incrementing, and busy for HCP65_LCD_POWER_ON_US.
// CGRAM isn't cleared.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::PowerOn(uint64 uiCycle)
{
	memset(mauiDDRAM, ' ', HCP65_LCD_DDRAM_SIZE);
	muiAddress = 0;
	mbCGRAM = false;
	mbIncrement = true;
	mbShiftOnWrite = false;
	mbDisplayOn = false;
	mbCursor = false;
	mbBlink = false;
	mbEightBit = true;
	mbTwoLines = false;
	mbLargeFont = false;
	muiShift = 0;
	mbLowNibble = false;
	muiHighNibble = 0;
	mbDataRead = false;
	muiDataRegister = 0;
	muiBusyUntil = 0;
	Busy(uiCycle, HCP65_LCD_POWER_ON_US);
}


//////////////////////////////////////////////////////////////////////////
//
// The pins as they are from uiCycle.  E falling ends a transfer: one that
// was a write takes uiDB (with RS and R/~W as they were while E was high).
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::SetPins(bool bE, bool bRS, bool bRead, uint8 uiDB, uint64 uiCycle)
{
	if (mbE && !bE)
	{
		if (!mbRead)
		{
			Transfer(mbRS, uiDB, uiCycle);
		}
		else
		{
			//A read is two transfers in four bit mode, the high four bits first.
			if (!mbEightBit)
			{
				mbLowNibble = !mbLowNibble;
			}
			if (mbDataRead && (mbEightBit || !mbLowNibble))
			{
				MoveAddress(mbIncrement);
				muiDataRegister = ReadData();
				Busy(uiCycle, HCP65_LCD_DATA_US);
			}
		}
		mbDataRead = false;
	}
	mbE = bE;
	mbRS = bRS;
	mbRead = bRead;
}


//////////////////////////////////////////////////////////////////////////
//
// The controller drives DB0-DB7 while E is high and R/~W is high.
//
//////////////////////////////////////////////////////////////////////////
bool CHCP65LCDController::IsDriving(void) const
{
	return mbE && mbRead;
}


//////////////////////////////////////////////////////////////////////////
//
// What it drives: the busy flag in D7 and the address counter, or the
// data register.  That was loaded from the address counter's RAM when
// the address was set, the cursor moved or the last read moved on, not
// by a write: a read straight after a write gives what was there before
// (the datasheet's note on Read Data).  In four bit mode the half of it
// this transfer is in D4-D7, and D0-D3 aren't driven.
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDController::GetOutput(uint64 uiCycle)
{
	uint8	uiValue;

	if (mbRS)
	{
		uiValue = muiDataRegister;
		mbDataRead = true;
	}
	else
	{
		uiValue = (uint8)(muiAddress & 0x7F);
		if (IsBusy(uiCycle))
		{
			uiValue |= 0x80;
		}
	}
	if (!mbEightBit)
	{
		uiValue = mbLowNibble ? (uint8)((uiValue << 4) | 0x0F) : (uint8)(uiValue | 0x0F);
	}
	return uiValue;
}


//////////////////////////////////////////////////////////////////////////
//
// A byte, or in four bit mode half of one, written to the instruction
// register (RS low) or as data.  Dropped while busy.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::Transfer(bool bRS, uint8 uiValue, uint64 uiCycle)
{
	if (!mbEightBit)
	{
		if (!mbLowNibble)
		{
			muiHighNibble = (uint8)(uiValue & 0xF0);
			mbLowNibble = true;
			return;
		}
		uiValue = (uint8)(muiHighNibble | (uiValue >> 4));
		mbLowNibble = false;
	}

	if (IsBusy(uiCycle))
	{
		muiIgnored++;
		return;
	}
	if (bRS)
	{
		WriteData(uiValue);
		Busy(uiCycle, HCP65_LCD_DATA_US);
	}
	else
	{
		Instruction(uiValue, uiCycle);
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::Instruction(uint8 uiValue, uint64 uiCycle)
{
	if (uiValue & 0x80)
	{
		//Set DDRAM address.
		muiAddress = (uint8)(uiValue & 0x7F);
		mbCGRAM = false;
		muiDataRegister = ReadData();
	}
	else if (uiValue & 0x40)
	{
		//Set CGRAM address.
		muiAddress = (uint8)(uiValue & 0x3F);
		mbCGRAM = true;
		muiDataRegister = ReadData();
	}
	else if (uiValue & 0x20)
	{
		//Function set: DL, N and F.  Four bit mode starts with the next transfer.
		mbEightBit = (uiValue & 0x10) != 0;
		mbTwoLines = (uiValue & 0x08) != 0;
		mbLargeFont = (uiValue & 0x04) != 0;
		mbLowNibble = false;
	}
	else if (uiValue & 0x10)
	{
		//Cursor or display shift: S/C and R/L.
		if (uiValue & 0x08)
		{
			ShiftDisplay((uiValue & 0x04) == 0);
		}
		else
		{
			MoveAddress((uiValue & 0x04) != 0);
			muiDataRegister = ReadData();
		}
	}
	else if (uiValue & 0x08)
	{
		//Display on/off control: D, C and B.
		mbDisplayOn = (uiValue & 0x04) != 0;
		mbCursor = (uiValue & 0x02) != 0;
		mbBlink = (uiValue & 0x01) != 0;
	}
	else if (uiValue & 0x04)
	{
		//Entry mode set: I/D and S.
		mbIncrement = (uiValue & 0x02) != 0;
		mbShiftOnWrite = (uiValue & 0x01) != 0;
	}
	else if (uiValue & 0x02)
	{
		//Return home.
		muiAddress = 0;
		mbCGRAM = false;
		muiShift = 0;
		Busy(uiCycle, HCP65_LCD_CLEAR_US);
		return;
	}
	else if (uiValue & 0x01)
	{
		//Clear display: spaces, the address counter 0 and incrementing, and no shift.
		memset(mauiDDRAM, ' ', HCP65_LCD_DDRAM_SIZE);
		muiAddress = 0;
		mbCGRAM = false;
		mbIncrement = true;
		muiShift = 0;
		Busy(uiCycle, HCP65_LCD_CLEAR_US);
		return;
	}
	Busy(uiCycle, HCP65_LCD_INSTRUCTION_US);
}


//////////////////////////////////////////////////////////////////////////
//
// The data at the address counter, which then moves; a DDRAM write
// shifts the display with it if the entry mode says to.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::WriteData(uint8 uiValue)
{
	if (mbCGRAM)
	{
		mauiCGRAM[muiAddress & 0x3F] = uiValue;
	}
	else
	{
		mauiDDRAM[DDRAMIndex(muiAddress)] = uiValue;
		if (mbShiftOnWrite)
		{
			ShiftDisplay(mbIncrement);
		}
	}
	MoveAddress(mbIncrement);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDController::ReadData(void) const
{
	if (mbCGRAM)
	{
		return mauiCGRAM[muiAddress & 0x3F];
	}
	return mauiDDRAM[DDRAMIndex(muiAddress)];
}


//////////////////////////////////////////////////////////////////////////
//
// The address counter one on or back.  On two lines DDRAM runs $00-$27
// then $40-$67 and round; on one, $00-$4F.  CGRAM runs $00-$3F.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::MoveAddress(bool bIncrement)
{
	if (mbCGRAM)
	{
		muiAddress = (uint8)((muiAddress + (bIncrement ? 1 : -1)) & 0x3F);
	}
	else if (mbTwoLines)
	{
		if (bIncrement)
		{
			muiAddress = (muiAddress == 0x27) ? HCP65_LCD_LINE_2 : (muiAddress == 0x67) ? 0x00 : (uint8)((muiAddress + 1) & 0x7F);
		}
		else
		{
			muiAddress = (muiAddress == 0x00) ? 0x67 : (muiAddress == HCP65_LCD_LINE_2) ? 0x27 : (uint8)((muiAddress - 1) & 0x7F);
		}
	}
	else
	{
		if (bIncrement)
		{
			muiAddress = (muiAddress >= 0x4F) ? 0x00 : (uint8)(muiAddress + 1);
		}
		else
		{
			muiAddress = (muiAddress == 0x00) ? 0x4F : (uint8)(muiAddress - 1);
		}
	}
}


//////////////////////////////////////////////////////////////////////////
//
// Both lines move together: left shows what is further on.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::ShiftDisplay(bool bLeft)
{
	uint8	uiLength;

	uiLength = mbTwoLines ? HCP65_LCD_LINE_LENGTH : HCP65_LCD_DDRAM_SIZE;
	if (bLeft)
	{
		muiShift = (uint8)((muiShift + 1) % uiLength);
	}
	else
	{
		muiShift = (uint8)((muiShift + uiLength - 1) % uiLength);
	}
}


//////////////////////////////////////////////////////////////////////////
//
// Where a DDRAM address is in its 80 bytes: the second line's $40-$67 is
// the same RAM as one line's $28-$4F.  Addresses past a line's end (which
// the controller doesn't have) fold back into it.
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDController::DDRAMIndex(uint8 uiAddress) const
{
	if (mbTwoLines)
	{
		if (uiAddress & HCP65_LCD_LINE_2)
		{
			return (uint8)(HCP65_LCD_LINE_LENGTH + (uiAddress & 0x3F) % HCP65_LCD_LINE_LENGTH);
		}
		return (uint8)((uiAddress & 0x3F) % HCP65_LCD_LINE_LENGTH);
	}
	return (uint8)(uiAddress % HCP65_LCD_DDRAM_SIZE);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::Busy(uint64 uiCycle, uint32 uiMicroseconds)
{
	muiBusyUntil = uiCycle + (muiCyclesPerSecond * uiMicroseconds + 999999) / 1000000;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CHCP65LCDController::IsBusy(uint64 uiCycle) const
{
	return uiCycle < muiBusyUntil;
}


uint8 CHCP65LCDController::GetAddress(void) const { return muiAddress; }
uint8 CHCP65LCDController::GetDDRAM(uint8 uiAddress) const { return mauiDDRAM[DDRAMIndex(uiAddress)]; }
uint8 CHCP65LCDController::GetCGRAM(uint8 uiAddress) const { return mauiCGRAM[uiAddress & 0x3F]; }
uint64 CHCP65LCDController::NumIgnored(void) const { return muiIgnored; }


//////////////////////////////////////////////////////////////////////////
//
// One row of a character's dots: CGRAM's for $00-$0F (eight characters,
// twice over), the ROM's for $20-$FF; $10-$1F are blank.
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDController::Glyph(uint8 uiCode, int iRow) const
{
	if (uiCode < 0x10)
	{
		return (uint8)(mauiCGRAM[((uiCode & 0x07) * HCP65_LCD_CHARACTER_HEIGHT) + iRow] & 0x1F);
	}
	if (uiCode >= HCP65_LCD_ROM_FIRST)
	{
		return gaauiHCP65LCDFont[uiCode - HCP65_LCD_ROM_FIRST][iRow];
	}
	return 0;
}


//////////////////////////////////////////////////////////////////////////
//
// What the display shows at uiCycle: the first line, and the second on
// two lines, from where the display is shifted to.  The cursor is the
// last row of the character at the address counter, and blinking makes
// that character all dots every other HCP65_LCD_BLINK_US.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDController::GetPicture(SHCP65LCDPicture* psPicture, uint64 uiCycle) const
{
	int		iRow;
	int		iColumn;
	int		iDot;
	uint8	uiAddress;
	uint8	uiCode;
	bool	bBlinkOn;
	uint64	uiBlinkCycles;

	memset(psPicture->aauiDots, 0, sizeof(psPicture->aauiDots));
	psPicture->bOn = mbDisplayOn;
	if (!mbDisplayOn)
	{
		return;
	}

	uiBlinkCycles = (muiCyclesPerSecond * HCP65_LCD_BLINK_US) / 1000000;
	bBlinkOn = (uiBlinkCycles == 0) || (((uiCycle / uiBlinkCycles) & 1) == 0);
	for (iRow = 0; iRow < (mbTwoLines ? HCP65_LCD_ROWS : 1); iRow++)
	{
		for (iColumn = 0; iColumn < HCP65_LCD_COLUMNS; iColumn++)
		{
			if (mbTwoLines)
			{
				uiAddress = (uint8)((iRow * HCP65_LCD_LINE_2) + ((iColumn + muiShift) % HCP65_LCD_LINE_LENGTH));
			}
			else
			{
				uiAddress = (uint8)((iColumn + muiShift) % HCP65_LCD_DDRAM_SIZE);
			}
			uiCode = mauiDDRAM[DDRAMIndex(uiAddress)];
			for (iDot = 0; iDot < HCP65_LCD_CHARACTER_HEIGHT; iDot++)
			{
				psPicture->aauiDots[iRow][iColumn][iDot] = Glyph(uiCode, iDot);
			}
			if (!mbCGRAM && (DDRAMIndex(uiAddress) == DDRAMIndex(muiAddress)))
			{
				if (mbCursor)
				{
					psPicture->aauiDots[iRow][iColumn][HCP65_LCD_CHARACTER_HEIGHT - 1] = 0x1F;
				}
				if (mbBlink && bBlinkOn)
				{
					memset(psPicture->aauiDots[iRow][iColumn], 0x1F, HCP65_LCD_CHARACTER_HEIGHT);
				}
			}
		}
	}
}


