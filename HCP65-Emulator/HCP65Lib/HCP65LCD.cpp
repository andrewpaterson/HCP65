// iController's buttons now, as HCP65_SNES_*: 0 for none pressed or for
// no controller plugged in.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDBoard::SetButtons(int iController, uint16 uiButtons)
{
	if ((iController >= 0) && (iController < HCP65_SNES_CONTROLLERS))
	{
		mauiButtons[iController] = (uint16)(uiButtons & HCP65_SNES_BUTTONS);
	}
}


//////////////////////////////////////////////////////////////////////////
//
// From any thread.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDBoard::GetPicture(SHCP65LCDPicture* psPicture, uint64 uiCycle)
{
	mcMutex.Lock();
	mcController.GetPicture(psPicture, uiCycle);
	mcMutex.Unlock();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CHCP65LCDBoard::IsBusy(void)
{
	bool	bBusy;

	mcMutex.Lock();
	bBusy = mcController.IsBusy(muiCycle);
	mcMutex.Unlock();
	return bBusy;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65LCDBoard::GetDDRAM(uint8 uiAddress)
{
	uint8	uiValue;

	mcMutex.Lock();
	uiValue = mcController.GetDDRAM(uiAddress);
	mcMutex.Unlock();
	return uiValue;
}


//////////////////////////////////////////////////////////////////////////
//
// Instructions and data the controller was given while busy.
//
//////////////////////////////////////////////////////////////////////////
uint64 CHCP65LCDBoard::NumIgnored(void)
{
	uint64	uiIgnored;

	mcMutex.Lock();
	uiIgnored = mcController.NumIgnored();
	mcMutex.Unlock();
	return uiIgnored;
}
