void CHCP65LCDBoard::Init(void)
{
	int		i;

	CHCP65Device::Init(HCP65_SMALL_SLOT_SIZE);
	mcROM.Init(HCP65_LCD_BOARD_NAME, HCP65_DEVICE_MANUFACTURER, 0, DEVICE_BUS_32KB, 0, HCP65_LCD_BOARD_DRIVER);
	mcROM.AddRegisters(HCP65_LCD_REGISTERS + HCP65_LCD_COMMAND, 8, DEVICE_REGISTER_READ);
	mcROM.AddRegisters(HCP65_LCD_REGISTERS + HCP65_LCD_COMMAND, 8, DEVICE_REGISTER_WRITE);
	mcROM.AddRegisters(HCP65_LCD_REGISTERS + HCP65_LCD_SNES_1_LOW, 4, DEVICE_REGISTER_READ);
	mcMutex.Init();
	mcController.Init(HCP65_DEFAULT_CLOCK_RATE);
	muiPins = 0;
	muiData = 0;
	muiCycle = 0;
	mbPoweredOn = false;
	for (i = 0; i < HCP65_SNES_CONTROLLERS; i++)
	{
		mauiButtons[i] = 0;
		mauiLatched[i] = 0;
	}
}


