//////////////////////////////////////////////////////////////////////////
//
// The display's power comes on with the HCP65's: its time starts at the
// first cycle the board sees, at the HCP65's clock rate.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65LCDBoard::PowerOn(void)
{
	if (mbPoweredOn)
	{
		return;
	}
	mbPoweredOn = true;
	mcMutex.Lock();
	mcController.Init(mpcHCP65 ? mpcHCP65->GetClockRate() : HCP65_DEFAULT_CLOCK_RATE);
	mcController.PowerOn(muiCycle);
	mcMutex.Unlock();
}


