//////////////////////////////////////////////////////////////////////////
//
// The device's bit in the Device Reset/Enable registers.  Held is a reset.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65Device::SetHeldInReset(bool bHeld)
{
	mbHeldInReset = bHeld;
	if (bHeld)
	{
		Reset();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CHCP65Device::IsHeldInReset(void)
{
	return mbHeldInReset;
}


