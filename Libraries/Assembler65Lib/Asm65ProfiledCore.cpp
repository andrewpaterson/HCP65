//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CAsm65ProfiledW65C816::Init(CAsm65Memory* pcMemory, CFastW65C816* pcFast)
{
	mpcMemory = pcMemory;
	mpcFast = pcFast;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65ProfiledW65C816::IsStopped(void)
{
	return mpcFast->IsStopped();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint64 CAsm65ProfiledW65C816::NumCycles(void)
{
	return mpcFast->NumCycles();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CAsm65ProfiledW65C816::GetProgramAddress(void)
{
	return mpcFast->GetProgramAddress();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CAsm65ProfiledW65C816::GetStack(void)
{
	return mpcFast->GetS();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CAsm65ProfiledW65C816::Step(void)
{
	mpcFast->Step();
}


//////////////////////////////////////////////////////////////////////////
//
// jsl, jsr, a jump, or the rtl a call through a pointer is made with
// (Asm65816IsCall).
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65ProfiledW65C816::IsCall(uint32 uiAddress)
{
	return Asm65816IsCall(mpcMemory->GetByte(uiAddress));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65ProfiledW65C816::IsReturn(uint32 uiAddress)
{
	return Asm65816IsReturn(mpcMemory->GetByte(uiAddress));
}


//////////////////////////////////////////////////////////////////////////
//
// A direct page operand: on the frame D points at.
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65ProfiledW65C816::HasFrameOperand(uint32 uiAddress)
{
	return Asm65816HasDirectPageOperand(mpcMemory->GetByte(uiAddress));
}


//////////////////////////////////////////////////////////////////////////
//
// tcd.
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65ProfiledW65C816::SetsFrame(uint32 uiAddress)
{
	return mpcMemory->GetByte(uiAddress) == 0x5B;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint16 CAsm65ProfiledW65C816::GetFrame(void)
{
	return mpcFast->GetD();
}


//////////////////////////////////////////////////////////////////////////
//
// label.axy: the registers its first words arrive in (s for a word left
// on the stack between them).
//
//////////////////////////////////////////////////////////////////////////
const char* CAsm65ProfiledW65C816::GetRegisterEntryLetters(void)
{
	return "axys";
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CAsm65Profiled65C64::Init(CAsm65Memory* pcMemory, CFast65C64* pcFast)
{
	mpcMemory = pcMemory;
	mpcFast = pcFast;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65Profiled65C64::IsStopped(void)
{
	return mpcFast->IsStopped();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint64 CAsm65Profiled65C64::NumCycles(void)
{
	return mpcFast->NumCycles();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CAsm65Profiled65C64::GetProgramAddress(void)
{
	return mpcFast->GetProgramCounter();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CAsm65Profiled65C64::GetStack(void)
{
	return mpcFast->GetS();
}


//////////////////////////////////////////////////////////////////////////
//
// One step of the instruction (a mul, div or block instruction takes
// several at one address).
//
//////////////////////////////////////////////////////////////////////////
void CAsm65Profiled65C64::Step(void)
{
	mpcFast->Step();
}


//////////////////////////////////////////////////////////////////////////
//
// jsr, brsr or jmp (instructions are at even addresses).
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65Profiled65C64::IsCall(uint32 uiAddress)
{
	return CFast65C64::IsCallOrJump(mpcMemory->GetWord(uiAddress & ~(uint32)1));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CAsm65Profiled65C64::IsReturn(uint32 uiAddress)
{
	return CFast65C64::IsReturn(mpcMemory->GetWord(uiAddress & ~(uint32)1));
}


//////////////////////////////////////////////////////////////////////////
//
// label.aby: the registers its first arguments arrive in (s for one left
// on the stack between them).
//
//////////////////////////////////////////////////////////////////////////
const char* CAsm65Profiled65C64::GetRegisterEntryLetters(void)
{
	return "abys";
}

